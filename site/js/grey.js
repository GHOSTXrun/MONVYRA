function greyout() {
  
  if(document.getElementById("greyimg")){
    var img = document.getElementById("greyimg");
    var wid = img.clientWidth;
    var left = parseInt(img.style.left);
    
    img.style.width = (wid - 100) + "px";
    
    img.classList.add("shrink");
    
    document.getElementById("greyimg").style.opacity = "0.5";
  
    document.getElementById('greyimg').id = 'done';
  } else  if(document.getElementById("done")){
      img = document.getElementById("done");
      wid = img.clientWidth;
  
      img.style.width = (wid + 100) + "px";
      
      img.classList.add("grow");
      
      document.getElementById('done').style.opacity = "1";
      
      document.getElementById('done').id = 'greyimg';
  }
  //for some reason the image scoots to the left on click 
}

